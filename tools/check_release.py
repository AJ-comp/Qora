#!/usr/bin/env python3
"""Release guard: keeps Qora's version numbers, changelogs, README samples and release history consistent.

CI runs it on every push and pull request, and the Release workflow runs it again before publishing:

    python tools/check_release.py --cli src/Qora/bin/Debug/net10.0/Qora.dll [--base-ref origin/main]
    python tools/check_release.py --cli src/Qora/bin/Debug/net10.0/Qora.dll --fix-samples
    python tools/check_release.py --plan-out plan.env --notes-out release-notes.md

What it checks (RELEASING.md explains the rules):

1. One Qora version (src/Qora.Core/Ir/QoraTypes.cs) and one extension version (vscode/package.json) are
   used wherever a version is written: the grammar header, package-lock.json, the top entries of both
   changelogs, the READMEs and docs/llms.txt. The top changelog entries contain no TODO. An entry titled
   "## Unreleased" may sit above them.
2. With --cli, every OpenQASM sample in README.md, README.ko.md and README.ja.md equals what the compiler
   emits for the Qora example right above it. --fix-samples rewrites the samples instead of failing.
3. Released history stays as released. For every tag vX.Y.Z: the changelog entries of that release are
   unchanged; a HEAD that still carries Qora X.Y.Z contains the tagged commit and the same extension
   version; HEAD's Qora version is not below the newest tag; and a new Qora version comes with a new
   extension version.
4. With --base-ref (branches and pull requests): the branch changes neither version. Versions change only
   in the release commit on main.

--plan-out and --notes-out are for the Release workflow: they write the versions, the tag and the commits
it needs as shell assignments, and the GitHub release notes (the CHANGELOG entry plus install links).
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shlex
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
QORA_TYPES = 'src/Qora.Core/Ir/QoraTypes.cs'
GRAMMAR = 'src/Qora.Core/QoraGrammar.cs'
PACKAGE = 'vscode/package.json'
LOCK = 'vscode/package-lock.json'
CHANGELOG = 'CHANGELOG.md'
EXT_CHANGELOG = 'vscode/CHANGELOG.md'
READMES = ('README.md', 'README.ko.md', 'README.ja.md')
EXT_READMES = ('vscode/README.md', 'vscode/README.ko.md', 'vscode/README.ja.md', 'vscode/README.vi.md')
LLMS = 'docs/llms.txt'

VERSION_CONST = re.compile(r'public const string Value = "(\d+\.\d+\.\d+)";')
DATED_HEADING = r'## {v} — \d{{4}}-\d{{2}}-\d{{2}}'
FENCE = re.compile(r'^```[^\n]*\n(.*?)^```[ \t]*$', re.M | re.S)
SAMPLE_HEADER = '// generated by Qora v'


def git(*args: str) -> str | None:
    """Run git in the repository; stdout without the trailing newline, or None if git fails."""
    result = subprocess.run(['git', *args], cwd=ROOT, capture_output=True, text=True, encoding='utf-8')
    return result.stdout.strip() if result.returncode == 0 else None


def read(path: str, rev: str | None = None) -> str | None:
    """A file from the working tree, or from a commit when rev is given; None if it does not exist."""
    if rev is None:
        file = ROOT / path
        return file.read_text(encoding='utf-8').replace('\r\n', '\n') if file.exists() else None
    result = subprocess.run(['git', 'show', f'{rev}:{path}'], cwd=ROOT, capture_output=True)
    return result.stdout.decode('utf-8').replace('\r\n', '\n') if result.returncode == 0 else None


def semver(text: str | None) -> tuple[int, int, int] | None:
    match = re.fullmatch(r'(\d+)\.(\d+)\.(\d+)', text or '')
    return tuple(int(part) for part in match.groups()) if match else None


def qora_version(rev: str | None = None) -> str | None:
    match = VERSION_CONST.search(read(QORA_TYPES, rev) or '')
    return match.group(1) if match else None


def ext_version(rev: str | None = None) -> str | None:
    try:
        return json.loads(read(PACKAGE, rev) or '')['version']
    except (ValueError, KeyError, TypeError):
        return None


def sections(text: str) -> dict[str, str]:
    """Changelog entries by version: each '## ' heading up to the next one, keyed by its first word."""
    heads = list(re.finditer(r'^## .*$', text, re.M))
    entries: dict[str, str] = {}
    for index, head in enumerate(heads):
        end = heads[index + 1].start() if index + 1 < len(heads) else len(text)
        words = head.group(0)[3:].split()
        if words:
            entries.setdefault(words[0], text[head.start():end].rstrip() + '\n')
    return entries


def top_entry(text: str) -> tuple[str, str] | None:
    """The newest released entry (heading line, entry text), skipping a leading '## Unreleased'."""
    heads = list(re.finditer(r'^## .*$', text, re.M))
    for index, head in enumerate(heads):
        if head.group(0).split()[1:2] == ['Unreleased']:
            continue
        end = heads[index + 1].start() if index + 1 < len(heads) else len(text)
        return head.group(0), text[head.start():end]
    return None


def tags() -> list[tuple[tuple[int, int, int], str]]:
    """Release tags vX.Y.Z, oldest first."""
    found = []
    for name in (git('tag', '--list', 'v*') or '').split():
        version = semver(name[1:])
        if version:
            found.append((version, name))
    return sorted(found)


def check_consistency(errors: list[str]) -> tuple[str | None, str | None]:
    q, e = qora_version(), ext_version()
    if not q:
        errors.append(f'{QORA_TYPES}: `public const string Value = "X.Y.Z";` is missing.')
    if not semver(e):
        errors.append(f'{PACKAGE}: "version" is missing or not X.Y.Z.')
    if not q or not semver(e):
        return q, e

    if f'/// Qora v{q} — ' not in (read(GRAMMAR) or ''):
        errors.append(f'{GRAMMAR}: the header must read "/// Qora v{q} — ...".')
    try:
        lock = json.loads(read(LOCK) or '')
        lock_versions = (lock.get('version'), lock.get('packages', {}).get('', {}).get('version'))
    except ValueError:
        lock_versions = (None, None)
    if lock_versions != (e, e):
        errors.append(f'{LOCK}: the root "version" entries must be {e} (found {lock_versions[0]}, {lock_versions[1]}).')

    for path, version, required, hint in (
            (CHANGELOG, q, f'VS Code extension **{e}** bundles the Qora {q} compiler.', 'language'),
            (EXT_CHANGELOG, e, f'Bundles **Qora {q}**', 'extension')):
        entry = top_entry(read(path) or '')
        if entry is None or not re.fullmatch(DATED_HEADING.format(v=re.escape(version)), entry[0]):
            found = entry[0] if entry else 'no entry'
            errors.append(f'{path}: the newest {hint} entry must be "## {version} — YYYY-MM-DD" (found "{found}").')
            continue
        if required not in entry[1]:
            errors.append(f'{path}: the {version} entry must say "{required}".')
        if 'TODO' in entry[1]:
            errors.append(f'{path}: the {version} entry still contains TODO.')

    for path in READMES:
        text = read(path) or ''
        for found in sorted(set(re.findall(r'generated by Qora v(\d+\.\d+\.\d+)', text)) - {q}):
            errors.append(f'{path}: an OpenQASM sample says "generated by Qora v{found}"; the compiler is {q}.')
        for found in sorted(set(re.findall(r'\(v0\.1 → v(\d+\.\d+\.\d+)\)', text)) - {q}):
            errors.append(f'{path}: the release-notes range ends at v{found}, not v{q}.')
        if f'**Qora {q}**' not in text:
            errors.append(f'{path}: the "what\'s new" lines near the top must name **Qora {q}**.')

    llms = read(LLMS) or ''
    if not llms.startswith(f'# Qora v{q} — '):
        errors.append(f'{LLMS}: the first line must start with "# Qora v{q} — ".')
    for found in sorted(set(re.findall(r'generated by Qora v(\d+\.\d+\.\d+)', llms)) - {q}):
        errors.append(f'{LLMS}: it says "generated by Qora v{found}"; the compiler is {q}.')

    for path in EXT_READMES:
        text = read(path) or ''
        if f'**{e}**' not in text or f'**Qora {q}**' not in text:
            errors.append(f'{path}: the version paragraph near the top must name extension **{e}** and **Qora {q}**.')
    return q, e


def compile_qora(cli: str, source: str) -> str:
    result = subprocess.run(['dotnet', cli, '--json'], input=source, capture_output=True, text=True, encoding='utf-8')
    try:
        data = json.loads(result.stdout)
    except ValueError:
        raise RuntimeError(f'the compiler at {cli} did not answer with JSON: {result.stderr.strip()[:300]}')
    if not data.get('success'):
        raise RuntimeError(f'the README example does not compile: {data.get("errors")}')
    return data['qasm'].replace('\r\n', '\n').rstrip('\n') + '\n'


def check_samples(errors: list[str], cli: str, fix: bool) -> None:
    for path in READMES:
        text = read(path)
        if text is None:
            continue
        blocks = list(FENCE.finditer(text))
        replacements = []
        for index, block in enumerate(blocks):
            if not block.group(1).startswith(SAMPLE_HEADER) or index == 0:
                continue
            try:
                expected = compile_qora(cli, blocks[index - 1].group(1))
            except RuntimeError as error:
                errors.append(f'{path}: {error}')
                continue
            if block.group(1) != expected:
                replacements.append((block.start(1), block.end(1), expected))
        if replacements and fix:
            for start, end, expected in reversed(replacements):
                text = text[:start] + expected + text[end:]
            (ROOT / path).write_text(text, encoding='utf-8')
            print(f'{path}: rewrote {len(replacements)} OpenQASM sample(s) from the compiler.')
        elif replacements:
            errors.append(f'{path}: {len(replacements)} OpenQASM sample(s) differ from the compiler output. '
                          f'Run: python tools/check_release.py --cli {cli} --fix-samples')


def is_ancestor(rev: str, head: str = 'HEAD') -> bool:
    return subprocess.run(['git', 'merge-base', '--is-ancestor', rev, head], cwd=ROOT).returncode == 0


def check_history(errors: list[str], notes: list[str], q: str, e: str) -> None:
    released = tags()
    if not released:
        notes.append('no release tags are available, so the history checks were skipped '
                     '(in CI, check out with fetch-depth: 0).')
        return
    lang_now, ext_now = sections(read(CHANGELOG) or ''), sections(read(EXT_CHANGELOG) or '')
    for version, tag in released:
        tag_q, tag_e = qora_version(tag), ext_version(tag)
        for path, entry_version, now in ((CHANGELOG, tag[1:], lang_now), (EXT_CHANGELOG, tag_e, ext_now)):
            then = sections(read(path, tag) or '').get(entry_version) if entry_version else None
            if then is not None and now.get(entry_version) != then:
                state = 'is missing here' if entry_version not in now else 'differs here'
                errors.append(f'{path}: the {entry_version} entry shipped in {tag} and must stay as released '
                              f'(it {state}). Put new changes in a new entry.')
        if tag_q is not None and tag_q != tag[1:]:
            notes.append(f'{tag} points at a commit whose Qora version is {tag_q}.')
        if q == tag[1:]:
            if not is_ancestor(tag):
                errors.append(f'Qora {q} was already released as {tag} from a different line of history. '
                              f'Do not reuse a released version; release this change as a new version on main.')
            elif tag_e is not None and e != tag_e:
                errors.append(f'{tag} shipped extension {tag_e} with Qora {q}, but this commit has extension {e}. '
                              f'The two versions move together: bump the Qora version as well.')
    newest, newest_tag = released[-1]
    if semver(q) < newest:
        errors.append(f'Qora {q} is lower than the newest release {newest_tag}.')
    elif semver(q) > newest:
        newest_e = ext_version(newest_tag)
        if newest_e and semver(e) <= semver(newest_e):
            errors.append(f'Qora {q} is a new release, so the extension version must also rise above {newest_e} '
                          f'(it is {e}).')


def check_branch(errors: list[str], q: str, e: str, base_ref: str) -> None:
    base = git('merge-base', 'HEAD', base_ref)
    if not base:
        errors.append(f'cannot find the merge base with {base_ref} (check out with fetch-depth: 0).')
        return
    base_q, base_e = qora_version(base), ext_version(base)
    if (base_q, base_e) != (q, e):
        errors.append(f'this branch changes the version (Qora {base_q} → {q}, extension {base_e} → {e}). '
                      f'Version numbers change only in the release commit on main; see RELEASING.md.')


def write_plan(q: str, e: str, plan_out: str | None, notes_out: str | None) -> None:
    tag = f'v{q}'
    tag_sha = git('rev-list', '-n', '1', f'refs/tags/{tag}') or ''
    intro_sha = git('log', '-1', '--format=%H', '-S', f'public const string Value = "{q}";', '--', QORA_TYPES) or ''
    earlier = [name for version, name in tags() if version < semver(q)]
    previous = earlier[-1] if earlier else ''
    title = f'Qora {q} / VS Code extension {e}'
    if plan_out:
        values = dict(qora=q, ext=e, tag=tag, tag_sha=tag_sha, intro_sha=intro_sha, previous_tag=previous, title=title)
        Path(plan_out).write_text(''.join(f'{key}={shlex.quote(value)}\n' for key, value in values.items()), encoding='utf-8')
    if notes_out:
        entry = sections(read(CHANGELOG) or '').get(q, '')
        body = entry.split('\n', 1)[1].strip() if '\n' in entry else ''
        package = json.loads(read(PACKAGE) or '{}')
        item = f'{package.get("publisher", "qora-lang")}.{package.get("name", "qora-language")}'
        server = os.environ.get('GITHUB_SERVER_URL', 'https://github.com')
        repo = os.environ.get('GITHUB_REPOSITORY', 'AJ-comp/Qora')
        lines = [body, '',
                 f'[Install from the VS Code Marketplace](https://marketplace.visualstudio.com/items?itemName={item}). '
                 'Offline VSIX packages for Windows x64, macOS arm64, and Linux x64 are attached below.']
        if previous:
            lines += ['', f'[Full changelog]({server}/{repo}/compare/{previous}...{tag})']
        Path(notes_out).write_text('\n'.join(lines) + '\n', encoding='utf-8')


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--cli', help='path to a built Qora.dll; compares the README OpenQASM samples with its output')
    parser.add_argument('--fix-samples', action='store_true', help='rewrite the README samples instead of failing (needs --cli)')
    parser.add_argument('--base-ref', help='on a branch or pull request: the main ref whose versions must be kept')
    parser.add_argument('--plan-out', help='write the release plan as shell assignments (Release workflow)')
    parser.add_argument('--notes-out', help='write the GitHub release notes (Release workflow)')
    args = parser.parse_args()
    if args.fix_samples and not args.cli:
        parser.error('--fix-samples needs --cli')

    errors: list[str] = []
    notes: list[str] = []
    q, e = check_consistency(errors)
    if args.cli:
        check_samples(errors, args.cli, args.fix_samples)
    if semver(q) and semver(e):
        check_history(errors, notes, q, e)
        if args.base_ref:
            check_branch(errors, q, e, args.base_ref)
    for note in notes:
        print(f'note: {note}')
    if errors:
        print(f'release guard: {len(errors)} problem(s)', file=sys.stderr)
        for error in errors:
            print(f'  - {error}', file=sys.stderr)
        return 1
    if args.plan_out or args.notes_out:
        write_plan(q, e, args.plan_out, args.notes_out)
    print(f'release guard: OK (Qora {q}, extension {e})')
    return 0


if __name__ == '__main__':
    sys.exit(main())
